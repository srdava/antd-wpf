/**
 * icon-gen: convert @ant-design/icons-svg path data into WPF Geometry fields.
 *
 * The icon package is not installed separately: antd already depends on it, so we read it
 * from the token-sync node_modules to keep one copy of the source of truth.
 *
 * Output: src/Antd.Wpf.Icons/Icons.g.cs
 * Usage:  node gen-icons.js [--all]
 */
const fs = require('fs');
const path = require('path');

const ASN_DIR = path.join(__dirname, '..', 'token-sync', 'node_modules', '@ant-design', 'icons-svg', 'lib', 'asn');
const OUT_FILE = path.join(__dirname, '..', '..', 'src', 'Antd.Wpf.Icons', 'Icons.g.cs');

// Curated first batch: the icons the M1 component set and the gallery actually use.
const CURATED = [
  'search', 'setting', 'user', 'home', 'menu', 'close', 'check', 'plus', 'minus',
  'down', 'up', 'left', 'right', 'double-left', 'double-right',
  'loading', 'reload', 'delete', 'edit', 'copy', 'download', 'upload',
  'info-circle', 'check-circle', 'close-circle', 'exclamation-circle', 'question-circle', 'warning',
  'eye', 'eye-invisible', 'lock', 'mail', 'phone', 'calendar', 'clock-circle',
  'file', 'folder', 'inbox', 'bell', 'star', 'heart', 'filter', 'sort-ascending',
  'more', 'ellipsis', 'plus-circle', 'arrow-up', 'arrow-down', 'send', 'cloud-upload',
  'safety-certificate', 'dashboard', 'appstore', 'link', 'printer', 'save', 'sync'
];

function pascal(name) {
  return name.split('-').map(part => part.charAt(0).toUpperCase() + part.slice(1)).join('');
}

function loadIcon(name) {
  const fileName = pascal(name) + 'Outlined.js';
  const file = path.join(ASN_DIR, fileName);
  if (!fs.existsSync(file)) return null;

  const mod = require(file);
  const definition = mod.default || mod;
  const children = (definition.icon && definition.icon.children) || [];

  const parts = [];
  let evenOdd = false;

  for (const child of children) {
    if (child.tag !== 'path' || !child.attrs || !child.attrs.d) continue;
    if (child.attrs['fill-rule'] === 'evenodd' || child.attrs['clip-rule'] === 'evenodd') {
      evenOdd = true;
    }
    parts.push(child.attrs.d.trim());
  }

  if (parts.length === 0) return null;
  const data = (evenOdd ? 'F1 ' : '') + parts.join(' ');
  return { name, field: pascal(name), data };
}

function csharpString(value) {
  return JSON.stringify(value);
}

const useAll = process.argv.includes('--all');
let names = CURATED;

if (useAll) {
  names = fs.readdirSync(ASN_DIR)
    .filter(f => f.endsWith('Outlined.js'))
    .map(f => f.replace(/Outlined\.js$/, ''))
    .map(n => n.replace(/([A-Z])/g, (m, p1, offset) => (offset ? '-' : '') + p1.toLowerCase()))
    .sort();
}

const icons = [];
const missing = [];
for (const name of names) {
  const icon = loadIcon(name);
  if (icon) icons.push(icon);
  else missing.push(name);
}

if (icons.length === 0) {
  console.error('No icons resolved. Check ASN_DIR: ' + ASN_DIR);
  process.exit(1);
}

const lines = [];
lines.push('// <auto-generated>');
lines.push('//   Generated by tools/icon-gen/gen-icons.js from @ant-design/icons-svg');
lines.push('//   ' + icons.length + ' outlined icons. Do not edit by hand.');
lines.push('// </auto-generated>');
lines.push('');
lines.push('using System;');
lines.push('using System.Collections.Generic;');
lines.push('using System.Windows.Media;');
lines.push('using System.Windows.Media.Effects;');
lines.push('');
lines.push('namespace Antd.Wpf.Icons');
lines.push('{');
lines.push('    /// <summary>');
lines.push('    /// Frozen icon geometries. Source SVGs use a 1024 viewBox offset by 64, so every');
lines.push('    /// geometry is translated into a 0..896 box to keep optical weight consistent.');
lines.push('    /// </summary>');
lines.push('    public static class AntdIcons');
lines.push('    {');
lines.push('        /// <summary>Side length of the normalised icon box.</summary>');
lines.push('        public const double BoxSize = 896;');
lines.push('');

// Lazily materialised: the full outlined set is ~400 icons, and parsing every geometry at type
// init would cost startup time for icons the app never draws.
for (const icon of icons) {
  lines.push('        public static Geometry ' + icon.field + ' { get { return Get(' + csharpString(icon.name) + '); } }');
}

lines.push('');
lines.push('        private static readonly Dictionary<string, string> Data =');
lines.push('            new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)');
lines.push('            {');
for (const icon of icons) {
  lines.push('                { ' + csharpString(icon.name) + ', ' + csharpString(icon.data) + ' },');
}
lines.push('            };');
lines.push('');
lines.push('        private static readonly Dictionary<string, Geometry> Cache =');
lines.push('            new Dictionary<string, Geometry>(StringComparer.OrdinalIgnoreCase);');
lines.push('');
lines.push('        /// <summary>Looks an icon up by its antd name, for example "search".</summary>');
lines.push('        public static Geometry ByName(string name)');
lines.push('        {');
lines.push('            return name == null ? null : Get(name);');
lines.push('        }');
lines.push('');
lines.push('        public static IEnumerable<string> Names');
lines.push('        {');
lines.push('            get { return Data.Keys; }');
lines.push('        }');
lines.push('');
lines.push('        private static Geometry Get(string name)');
lines.push('        {');
lines.push('            Geometry cached;');
lines.push('            if (Cache.TryGetValue(name, out cached)) return cached;');
lines.push('');
lines.push('            string data;');
lines.push('            if (!Data.TryGetValue(name, out data)) return null;');
lines.push('');
lines.push('            Geometry geometry = Create(data);');
lines.push('            Cache[name] = geometry;');
lines.push('            return geometry;');
lines.push('        }');
lines.push('');lines.push('        private static Geometry Create(string data)');
lines.push('        {');
lines.push('            // Geometry.Parse returns an already frozen StreamGeometry, so the viewBox');
lines.push('            // offset has to live on a wrapping group instead of the geometry itself.');
lines.push('            var group = new GeometryGroup();');
lines.push('            group.Transform = new TranslateTransform(-64, -64);');
lines.push('            group.Children.Add(Geometry.Parse(data));');
lines.push('            group.Freeze();');
lines.push('            return group;');
lines.push('        }');
lines.push('    }');
lines.push('}');
lines.push('');

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, lines.join('\n'), 'utf8');

console.log('icons: ' + icons.length + ' -> ' + path.relative(path.join(__dirname, '..', '..'), OUT_FILE));
if (missing.length) console.log('missing: ' + missing.join(', '));
