/**
 * token-sync: dump Ant Design design tokens as golden data.
 *
 * Output:
 *   out/tokens.golden.json   - human readable, for review
 *   out/GoldenTokens.g.cs    - generated C#, consumed by Antd.Wpf.Tests (no JSON parser needed)
 *
 * Usage: node dump-tokens.js
 */
const fs = require('fs');
const path = require('path');

const themeModule = require('antd/lib/theme');
const theme = themeModule.default || themeModule;
const pkg = require('antd/package.json');

const CONFIGS = {
  default: {},
  dark: { algorithm: theme.darkAlgorithm },
  compact: { algorithm: theme.compactAlgorithm },
  darkCompact: { algorithm: [theme.darkAlgorithm, theme.compactAlgorithm] },
  customPrimary: { token: { colorPrimary: '#00b96b' } },
  customRadius8: { token: { borderRadius: 8 } },
  customFontSize16: { token: { fontSize: 16 } },
  customBgBase: { token: { colorBgBase: '#123456' } },
  customTextBase: { token: { colorTextBase: '#333333' } },
  darkPurple: { algorithm: theme.darkAlgorithm, token: { colorPrimary: '#9254de' } },
};

function flatten(tokens) {
  const out = {};
  for (const key of Object.keys(tokens)) {
    const value = tokens[key];
    if (value === undefined || value === null) continue;
    if (typeof value === 'string' || typeof value === 'number' || typeof value === 'boolean') {
      out[key] = typeof value === 'number' ? roundNumber(value) : value;
    }
  }
  return out;
}

function roundNumber(n) {
  if (Number.isInteger(n)) return n;
  return Math.round(n * 1e6) / 1e6;
}

function csharpString(s) {
  // JSON escaping is a subset of C# string escaping (\n, \", \\, \t, \uXXXX).
  return JSON.stringify(String(s));
}

const result = { antdVersion: pkg.version, generatedAt: new Date().toISOString(), configs: {} };
for (const [name, cfg] of Object.entries(CONFIGS)) {
  result.configs[name] = flatten(theme.getDesignToken(cfg));
}

const outDir = path.join(__dirname, 'out');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'tokens.golden.json'), JSON.stringify(result, null, 2), 'utf8');

const lines = [];
lines.push('// <auto-generated>');
lines.push('//   Generated by tools/token-sync/dump-tokens.js');
lines.push('//   antd ' + result.antdVersion + ' @ ' + result.generatedAt);
lines.push('//   Do not edit by hand. Re-run the generator instead.');
lines.push('// </auto-generated>');
lines.push('');
lines.push('using System.Collections.Generic;');
lines.push('');
lines.push('namespace Antd.Wpf.Tests.Generated');
lines.push('{');
lines.push('    internal static class GoldenTokens');
lines.push('    {');
lines.push('        public const string AntdVersion = ' + csharpString(result.antdVersion) + ';');
lines.push('');
lines.push('        public static readonly Dictionary<string, Dictionary<string, string>> Configs =');
lines.push('            new Dictionary<string, Dictionary<string, string>>');
lines.push('            {');
for (const [name, tokens] of Object.entries(result.configs)) {
  lines.push('                {');
  lines.push('                    ' + csharpString(name) + ',');
  lines.push('                    new Dictionary<string, string>');
  lines.push('                    {');
  for (const key of Object.keys(tokens).sort()) {
    lines.push('                        { ' + csharpString(key) + ', ' + csharpString(tokens[key]) + ' },');
  }
  lines.push('                    }');
  lines.push('                },');
}
lines.push('            };');
lines.push('    }');
lines.push('}');
lines.push('');

fs.writeFileSync(path.join(outDir, 'GoldenTokens.g.cs'), lines.join('\n'), 'utf8');

const counts = Object.entries(result.configs).map(([k, v]) => k + '=' + Object.keys(v).length).join(', ');
console.log('antd ' + result.antdVersion);
console.log('configs: ' + counts);
console.log('written: out/tokens.golden.json, out/GoldenTokens.g.cs');
